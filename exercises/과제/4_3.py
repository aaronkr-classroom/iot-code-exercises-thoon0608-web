# 합계를 저장할 변수 초기화
sum = 0
i = 0

# i가 50보다 작을 동안 반복 (결과적으로 1~50까지 확인)
while i < 50:
    i += 1  # 다음 숫자로 넘어감
    
    # 짝수인지 확인
    if i % 2 == 0:
        
        # 3으로 나누어떨어지는 숫자(3의 배수)이면 제외
        if i % 3 == 0:
            continue
            
        # 3의 배수가 아닌 짝수만 합계에 더함
        sum += i

# 합계 출력
print(sum)